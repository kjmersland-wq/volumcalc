const LABELS: Record<Lang, Labels> = { en, no, sv, da, fi, de, nl, fr, pl, es, it, pt };

export function xl(lang: Lang, key: LabelKey, vars?: Record<string, string | number>): string {
  let text = (LABELS[lang] ?? en)[key] ?? en[key];
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, String(value));
  return text;
}
