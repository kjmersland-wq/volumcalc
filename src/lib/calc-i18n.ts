/** Name of a predefined room in `lang`; custom rooms keep the visitor's own name. */
export function roomLabel(lang: Lang, id: string, fallback: string): string {
  const index = ROOM_IDS.indexOf(id);
  return index === -1 ? fallback : (ROOM_NAMES[lang] ?? ROOM_NAMES.en)[index] ?? fallback;
}
